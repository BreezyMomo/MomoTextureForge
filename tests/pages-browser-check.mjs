// Run after npm run build:pages. Serve only the built HTML under a Pages-style prefix.
import http from 'node:http';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {BUILTIN} from '../web/definition-runtime.js';
import {GENERATOR_EXAMPLE} from '../web/generator-authoring.js';
import {project,node} from '../web/tree-model.js';
import {treeSamples} from '../web/tree-samples.js';

const html=await readFile(new URL('../site/index.html',import.meta.url));
const prefix='/MomoTextureForge/';
const server=http.createServer((request,response)=>{
 const path=new URL(request.url,'http://localhost').pathname;
 if(path!==prefix&&path!==prefix+'index.html'){response.writeHead(404);response.end();return;}
 response.setHeader('Content-Type','text/html; charset=utf-8');response.end(html);
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let browser;
try{
 browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],requests=[],workers=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('request',request=>{if(/^https?:/.test(request.url()))requests.push({url:request.url(),type:request.resourceType()});});
 page.on('worker',worker=>workers.push(worker.url()));
 const address='http://127.0.0.1:'+server.address().port+prefix;
 const ready=async()=>{await page.waitForFunction(()=>document.documentElement.dataset.ready==='true',null,{timeout:120000});};
 await page.goto(address);await ready();
 assert.equal(await page.locator('[role="treeitem"]').count(),0,'first visit starts with an empty canvas');
 await page.locator('#open-graphics-library').click();
 await page.waitForFunction(count=>document.querySelectorAll('.graphics-card[data-origin="builtin"]').length===count,BUILTIN.catalog.length,{timeout:30000});
 assert.equal(await page.locator('.graphics-card[data-origin="builtin"]').count(),BUILTIN.catalog.length);
 const editGraphic=async name=>{
  const card=page.locator('.graphics-card').filter({has:page.locator('strong').getByText(name,{exact:true})});
  await card.locator('.graphics-card-details>summary').click();await card.getByRole('button',{name:'编辑 '+name,exact:true}).click();
 };
 await page.getByPlaceholder('搜索名称、分类或标签').fill('湍流火焰');
 await editGraphic('湍流火焰');
 const generatorDialog=page.locator('dialog.graphic-editor-dialog');await generatorDialog.getByRole('status').filter({hasText:'预览成功'}).waitFor();
 const generatorColors=await generatorDialog.locator('canvas').evaluate(canvas=>{const data=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;let colors=0;for(let i=0;i<data.length;i+=4)if(data[i+3]>8&&data[i]>data[i+2]+20)colors++;return colors;});assert.ok(generatorColors>0,'embedded generator retains fire colors');
 await generatorDialog.locator('header .graphics-close').click();
 await page.getByPlaceholder('搜索名称、分类或标签').fill('跃动篝火');await editGraphic('跃动篝火');
 const dynamicDialog=page.locator('dialog.graphic-editor-dialog');await dynamicDialog.getByRole('status').filter({hasText:'预览成功'}).waitFor();
 const beforeMotion=await dynamicDialog.locator('canvas').evaluate(c=>c.toDataURL());await dynamicDialog.getByRole('slider',{name:'预览时间（秒）',exact:true}).press('End');
 await page.waitForFunction(before=>document.querySelector('dialog.graphic-editor-dialog canvas')?.toDataURL()!==before,beforeMotion);
 await dynamicDialog.locator('header .graphics-close').click();
 await page.getByPlaceholder('搜索名称、分类或标签').fill('');
 await page.locator('.graphics-management>summary').click();await page.getByRole('button',{name:'创建资源',exact:true}).click();const customDialog=page.locator('dialog.resource-create-dialog');await customDialog.getByRole('tab',{name:'生成器',exact:true}).click();
 await customDialog.getByRole('status').filter({hasText:'预览成功'}).waitFor();await customDialog.getByRole('textbox',{name:'生成器JSON',exact:true}).fill(JSON.stringify(GENERATOR_EXAMPLE));
 await customDialog.getByRole('button',{name:'验证并预览',exact:true}).click();await customDialog.getByRole('slider',{name:'半径滑动条'}).waitFor();await customDialog.getByRole('status').filter({hasText:'预览成功'}).waitFor();
 const customPixels=await customDialog.locator('section:not([hidden]) .graphic-preview-panel canvas').evaluate(c=>c.getContext('2d').getImageData(0,0,c.width,c.height).data.filter((v,i)=>i%4===3&&v>5).length);assert.ok(customPixels>100,'custom pipeline works inside standalone HTML');
 await customDialog.getByRole('button',{name:'导入图形库',exact:true}).click();await customDialog.waitFor({state:'detached'});assert.ok(await page.locator('.graphics-card[data-origin="local"]').filter({hasText:GENERATOR_EXAMPLE.name}).count());
 // A new navigation closes the modal while keeping the same hosted path.
 await page.goto(address);await ready();
 await page.locator('#export-now').click();
 const downloadPromise=page.waitForEvent('download',{timeout:120000});
 await page.locator('#confirm-export').click();
 const download=await downloadPromise;
 assert.equal(await download.failure(),null);
 const png=await readFile(await download.path());
 assert.deepEqual([...png.subarray(0,8)],[137,80,78,71,13,10,26,10]);
 assert.ok(workers.some(url=>url.startsWith('blob:')),'export must work with the embedded worker');
 const materialProject=project();materialProject.root.children=[node('shape','VolumeSmoke')];materialProject.root.children[0].postFx[1]=.3;materialProject.output.normalAlgorithm='scharr';materialProject.output.normalFlipY=true;
 await page.goto(address+'#tree='+Buffer.from(JSON.stringify(materialProject)).toString('base64'));await page.reload();await ready();
 const beforeChannel=await page.evaluate(()=>localStorage.getItem('momo-texture-tree:draft:v1'));
 await page.getByRole('combobox',{name:'预览贴图类型',exact:true}).selectOption('normal');
 assert.equal(await page.locator('#normal-preview-settings').isVisible(),true);
 assert.equal(await page.locator('#normal-preview-settings').getByRole('combobox',{name:'法线算法',exact:true}).inputValue(),'scharr');
 assert.equal(await page.evaluate(()=>localStorage.getItem('momo-texture-tree:draft:v1')),beforeChannel);
 await page.locator('#export-now').click();assert.equal(await page.locator('#global-panel').getByRole('combobox',{name:'输出内容',exact:true}).inputValue(),'color');await page.locator('#close-global').click();
 await page.getByRole('combobox',{name:'预览模式',exact:true}).selectOption('material');await page.waitForFunction(()=>document.querySelector('#render-status').textContent.includes('材质采样'));await page.getByRole('combobox',{name:'预览模型'}).selectOption('2');await page.getByRole('combobox',{name:'预览模式',exact:true}).selectOption('canvas');
 await page.goto(address+'?view=examples');await ready();
 assert.equal(await page.locator('a[href]').first().getAttribute('href'),address);
 // Examples generate on navigation; wait for that work instead of clicking a disabled button.
 await page.waitForFunction(count=>!document.querySelector('#generate')?.disabled&&document.querySelectorAll('#samples article').length===count,treeSamples().length,{timeout:180000});
 const exampleLink=await page.locator('#samples article a').first().getAttribute('href');
 const exampleURL=new URL(exampleLink);assert.equal(exampleURL.origin+exampleURL.pathname,address);assert.ok(exampleURL.hash.startsWith('#tree='));
 await page.goto(exampleLink);await ready();
 if(exampleURL.searchParams.has('preview-time'))assert.equal(Number(await page.locator('#tree-time').inputValue()),Number(exampleURL.searchParams.get('preview-time')),'example opens at its authored preview time');
 const exampleNodes=await page.locator('[role="treeitem"]').count();assert.ok(exampleNodes>2);
 await page.locator('details.header-dropdown > summary').filter({hasText:'文件'}).click();
 await page.locator('#new-project').click();
 assert.equal(await page.locator('[role="treeitem"]').count(),0,'new project has no default shape');
 await page.locator('#undo').click();
 assert.equal(await page.locator('[role="treeitem"]').count(),exampleNodes,'undo restores the previous artwork');
 await page.locator('#redo').click();
 assert.equal(await page.locator('[role="treeitem"]').count(),0);
 await page.goto(address);await ready();
 assert.equal(await page.locator('[role="treeitem"]').count(),0,'empty draft stays empty after reopening');
 await page.locator('#add-group').click();
 assert.equal(await page.locator('[role="treeitem"]').count(),1,'nodes can still be added to an empty project');
 await page.goto(address+'?view=validate');await ready();
 assert.equal(await page.locator('a[href]').first().getAttribute('href'),address);
 assert.ok(await page.locator('#composite').count());
 assert.deepEqual(errors,[]);
 assert.ok(requests.every(request=>request.type==='document'&&new URL(request.url).pathname===prefix),JSON.stringify(requests));
 const report={builtins:BUILTIN.catalog.length,views:['editor','examples','validate'],emptyNewProject:true,undoNewProject:true,pngExport:png.length,embeddedWorker:true,embeddedGenerator:true,dynamicGenerator:true,materialPreview:true,customGenerator:true,customPixels,generatorColors,externalAssets:0,errors};
 await mkdir(new URL('../test-results/pages/',import.meta.url),{recursive:true});
 await writeFile(new URL('../test-results/pages/report.json',import.meta.url),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
