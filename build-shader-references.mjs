import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
export async function buildShaderReferences(){
 const files={};
 for(const name of ['handdrawn-fill.hlsl','HanddrawnFillURP.shader','MomoHanddrawnImporter.cs','README.md','README.en.md'])files[name]=await readFile(new URL('./web/shaders/'+name,import.meta.url),'utf8');
 await writeFile(new URL('./web/shader-reference-runtime.js',import.meta.url),'// Generated by build-shader-references.mjs; do not edit.\nexport default '+JSON.stringify(files)+';\n');return files;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await buildShaderReferences();
