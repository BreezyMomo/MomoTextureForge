import {buildEffectsKit} from './build-effects-kit.mjs';
import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadDefinitionURL} from './web/definition-loader.js';
import {AUTHORING_SKILL,AUTHORING_GUIDE,AUTHORING_EXAMPLE} from './web/ai-authoring.js';
import {GENERATOR_EXAMPLE} from './web/generator-authoring.js';
import {encodeZIP} from './web/encoders.js';
const root=dirname(fileURLToPath(import.meta.url));
export async function buildAuthoringKit(){
 const registry=await loadDefinitionURL(new URL('./web/definitions/builtin.json',import.meta.url));
 await buildEffectsKit(registry);
 const plugin={name:'embedded-definitions',setup(b){b.onLoad({filter:/definition-runtime\.js$/},()=>({contents:`export const BUILTIN=${JSON.stringify(registry)};export const formulaText=spec=>spec.inline??BUILTIN.sources[spec.file];`,loader:'js'}));}};
 const bundle=async(file,platform)=>{const r=await build({absWorkingDir:root,entryPoints:[file],bundle:true,write:false,format:'esm',platform,target:'es2022',minify:true,external:platform==='node'?['playwright']:[],plugins:[plugin]});return r.outputFiles[0].text;};
 const pkg=JSON.parse(await readFile(resolve(root,'package.json'),'utf8'));
 const runtime={
  'scripts/texforge.mjs':await bundle('portable-authoring-cli.mjs','node'),
  'scripts/web/authoring-render.js':await bundle('web/authoring-render.js','browser'),
  'scripts/web/authoring-render.html':await readFile(resolve(root,'web/authoring-render.html'),'utf8'),
  'package.json':JSON.stringify({name:'texture-forge-author',private:true,type:'module',engines:{node:'>=22'},dependencies:{playwright:pkg.devDependencies.playwright.replace(/^[~^]/,'')}},null,2),
  'references/generator-guide.md':await readFile(resolve(root,'skills/texture-forge-author/references/generator-guide.md'),'utf8'),
  'references/example.generator.json':JSON.stringify(GENERATOR_EXAMPLE,null,2)+'\n',
 };
 await writeFile(resolve(root,'web/authoring-kit-runtime.js'),'// Generated by build-authoring-kit.mjs; do not edit.\nexport default '+JSON.stringify(runtime)+';\n');
 const files={...runtime,'SKILL.md':AUTHORING_SKILL+'\n','references/authoring-guide.md':AUTHORING_GUIDE+'\n','references/example.graphic.json':JSON.stringify(AUTHORING_EXAMPLE,null,2)+'\n'};
 for(const [name,text]of Object.entries(files)){const path=resolve(root,'skills/texture-forge-author',name);await mkdir(dirname(path),{recursive:true});await writeFile(path,text);}
 await mkdir(resolve(root,'dist'),{recursive:true});
 await writeFile(resolve(root,'dist/texture-forge-ai-skill.zip'),encodeZIP(Object.entries(files).map(([name,text])=>({name:'texture-forge-author/'+name,data:new TextEncoder().encode(text)}))));
 return files;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await buildAuthoringKit();
